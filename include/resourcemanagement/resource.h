/*============================================================================================================

    リソース基底クラス [resource.h]
    すべてのリソース（Mesh、Material、Textureなど）の共通基底クラス。
    ファイル名とクラスIDを管理し、リソースの一元管理を可能にする。

    Author : Ryosuke Kageyama
    Date   : 2025/11/25

=============================================================================================================*/
#ifndef RESOURCE_H
#define RESOURCE_H

#include <string>

/*============================================================================================================
    リソースクラスID列挙型
    各リソースタイプを識別するための列挙型
=============================================================================================================*/
enum class ResourceClassID
{
    Unknown = 0,    // 不明なリソースタイプ
    Mesh,           // メッシュリソース
    Material,       // マテリアルリソース
    Texture,        // テクスチャリソース
	Model,          // 3Dモデルリソース
    Shader,         // シェーダーリソース（将来的な拡張用）
    Audio,          // オーディオリソース（将来的な拡張用）
    
    Count           // リソースタイプ数（配列サイズ計算用）
};

/*============================================================================================================
    リソース基底クラス
    すべてのリソースが継承すべき基底クラス。
    ファイル名とクラスIDを管理し、リソースマネージャーによる一元管理を可能にする。
=============================================================================================================*/
class Resource
{
public:
    // デフォルトコンストラクタ
    Resource();
    
    // クラスIDを指定するコンストラクタ
    Resource(ResourceClassID classID);
    
    // 識別名とクラスIDを指定するコンストラクタ
    // 引数:
    //   name - リソースの識別名
    //   classID - リソースのクラスID
    Resource(const std::wstring& name, ResourceClassID classID);
    
    // 仮想デストラクタ（派生クラスの適切な破棄のため）
    virtual ~Resource() = default;

    /*========================================================================================================
        ゲッター関数群
    ========================================================================================================*/
    
    // クラスIDを取得する
    // 戻り値: リソースのクラスID（ResourceClassID列挙型）
    ResourceClassID GetClassID() const;
    
    // 識別名を取得する
    // 戻り値: リソースの識別名
    const std::wstring& GetName() const;

    /*========================================================================================================
        セッター関数群
    ========================================================================================================*/
    
    // クラスIDを設定する
    // 引数:
    //   classID - 設定するクラスID（ResourceClassID列挙型）
    void SetClassID(ResourceClassID classID);
    
    // 識別名を設定する
    // 引数:
    //   name - 設定する識別名
    void SetName(const std::wstring& name);

    /*========================================================================================================
        純粋仮想関数（派生クラスで実装必須）
    ========================================================================================================*/
    
    // リソースを解放する
    // 派生クラスでリソース固有の解放処理を実装する
    virtual void Release() = 0;
    
    // リソースが有効かどうかを判定する
    // 戻り値: リソースが有効な場合true、無効な場合false
    virtual bool IsValid() const = 0;

protected:
    ResourceClassID m_ClassID;      // リソースのクラスID（リソース型の識別）
    std::wstring m_Name;            // リソースの識別名（キャッシュキーとして使用）
};
#endif
