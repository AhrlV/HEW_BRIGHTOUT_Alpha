/*============================================================================================================

    マテリアルクラス [material.h]
    3Dモデルの表面の材質情報を管理するクラス。
    色、テクスチャ、シェーダー、レンダリングステートなどを保持する。

    Author : Ryosuke Kageyama
    Date   : 2025/11/25

=============================================================================================================*/
#ifndef MATERIAL_H
#define MATERIAL_H

#include <d3d11.h>
#include <wrl/client.h>
#include <DirectXMath.h>
#include <memory>
#include "resourcemanagement/resource.h"
#include "resourcemanagement/texture.h"

// 前方宣言
class PixelShader;

/*============================================================================================================
    マテリアルクラス
    3Dモデルの材質情報を管理する。
    Resourceクラスを継承し、ResourceManagerによる一元管理が可能。
=============================================================================================================*/
class Material : public Resource
{
public:
	/*========================================================================================================
	    マテリアルプロパティ（デフォルト値付き）
	========================================================================================================*/
	
	// 基本カラー（RGBA）- デフォルト: 白
	DirectX::XMFLOAT4 BaseColor;
	
	// 拡散反射色（RGBA）- デフォルト: 白
	DirectX::XMFLOAT4 DiffuseColor;
	
	// 環境光色（RGBA）- デフォルト: グレー
	DirectX::XMFLOAT4 AmbientColor;
	
	// 鏡面反射色（RGBA）- デフォルト: 白
	DirectX::XMFLOAT4 SpecularColor;
	
	// 放射色（RGBA）- デフォルト: 黒
	DirectX::XMFLOAT4 EmissiveColor;
	
	// 光沢度 - デフォルト: 32.0
	float Shininess;
	
	// 不透明度 - デフォルト: 1.0（完全不透明）
	float Opacity;
	
	// メタリック度 - デフォルト: 0.0（非金属）
	float Metallic;
	
	// 粗さ - デフォルト: 0.5
	float Roughness;
	
	// テクスチャ
	std::shared_ptr<Texture> Texture;

	// デフォルトコンストラクタ
	Material();
	
	// 識別名を指定するコンストラクタ
	// 引数:
	//   name - このマテリアルの識別名（ファイル名やキャッシュキーなど）
	explicit Material(const std::wstring& name);
	
	// デストラクタ
	~Material() override;

	/*========================================================================================================
	    マテリアルの初期化
	    デフォルトのブレンドステート、深度ステート、サンプラーステートを作成する。
	    
	    引数:
	    戻り値: 初期化に成功した場合true
	========================================================================================================*/
	bool Initialize();

	/*========================================================================================================
	    Resource基底クラスのオーバーライド
	========================================================================================================*/
	
	// リソースを解放する
	void Release() override;
	
	// リソースが有効かどうかを判定する
	// 戻り値: マテリアルが有効な場合true
	bool IsValid() const override;

	/*========================================================================================================
	    シェーダー設定
	========================================================================================================*/
	
	// ピクセルシェーダーを設定する
	// 引数:
	//   ps - 設定するピクセルシェーダーのshared_ptr
	void SetPixelShader(std::shared_ptr<PixelShader> ps);
	
	// ピクセルシェーダーを取得する
	// 戻り値: ピクセルシェーダーのshared_ptr
	std::shared_ptr<PixelShader> GetPixelShader() const;

	/*========================================================================================================
	    レンダリングステート取得
	========================================================================================================*/
	
	// ブレンドステートを取得する
	// 戻り値: ブレンドステートのポインタ
	ID3D11BlendState* GetBlendState() const;
	
	// 深度ステンシルステートを取得する
	// 戻り値: 深度ステンシルステートのポインタ
	ID3D11DepthStencilState* GetDepthState() const;
	
	// サンプラーステートを取得する
	// 戻り値: サンプラーステートのポインタ
	ID3D11SamplerState* GetSampler() const;

	/*========================================================================================================
	    レンダリングステート再作成
	    ブレンドステートと深度ステンシルステートを再作成する。
	========================================================================================================*/
	void RecreateStates();

	/*========================================================================================================
	    シェーダー定数バッファ更新
	========================================================================================================*/
	
	// ピクセルシェーダーのPerMaterial定数バッファを更新する
	// マテリアルの色情報をシェーダーに送信する。
	// 引数:
	//   pixelShader - 更新対象のピクセルシェーダー
	// 例外: 更新に失敗した場合はruntime_errorをスロー
	void UpdatePixelShaderPerMaterial(PixelShader* pixelShader) const;

private:
	/*========================================================================================================
	    レンダリングステート作成（プライベート）
	========================================================================================================*/
	
	// ブレンドステートを作成する（アルファブレンド無効）
	void CreateBlendState();
	
	// 深度ステンシルステートを作成する（深度テスト有効）
	void CreateDepthState();
	
	// デフォルトのサンプラーステートを作成する（線形補間、ラップモード）
	void CreateDefaultSampler();

	/*========================================================================================================
	    プライベートメンバ変数
	========================================================================================================*/
	
	// ピクセルシェーダー（shared_ptrで管理）
	std::shared_ptr<PixelShader> m_PixelShader;

	// テクスチャサンプラーステート
	Microsoft::WRL::ComPtr<ID3D11SamplerState> m_Sampler;

	// ブレンドステート
	Microsoft::WRL::ComPtr<ID3D11BlendState> m_BlendState;
	
	// 深度ステンシルステート
	Microsoft::WRL::ComPtr<ID3D11DepthStencilState> m_DepthState;
};

#endif // MATERIAL_H
