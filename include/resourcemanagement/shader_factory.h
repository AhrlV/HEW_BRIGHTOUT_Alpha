/*============================================================================================================

    シェーダーファクトリー [shader_factory.h]
    Shaderリソースの生成と管理を行うファクトリークラス。
    ResourceManagerと連携して、リソースの一元管理とキャッシュ機能を提供。

    Author : Ryosuke Kageyama
    Date   : 2025/11/26

=============================================================================================================*/
#ifndef SHADER_FACTORY_H
#define SHADER_FACTORY_H

#include <memory>
#include <string>
#include <vector>
#include <d3d11.h>
#include <d3dcommon.h>
#include <wrl/client.h>

// 前方宣言
class VertexShader;
class PixelShader;
class Shader;

/*============================================================================================================
    ShaderFactoryクラス
    Shaderリソースの生成と管理を行うファクトリークラス。
    ResourceManagerに問い合わせ、キャッシュされていればそれを返し、
    なければファイルから読み込んでResourceManagerに登録する。
    ファイルパスには自動的に"shaders/cso/"を先頭に付加する。
=============================================================================================================*/
class ShaderFactory
{
public:
	/*========================================================================================================
		頂点シェーダーの生成または取得
		
		ResourceManagerに登録されている頂点シェーダーを取得する。
		登録されていない場合は、ファイルから読み込んでResourceManagerに登録する。
		ファイルパスには自動的に"shaders/cso/"を先頭に付加する。
		
		引数:
		  filename - シェーダーファイルのパス("shaders/cso/"は自動付加)
		  inputLayout - 入力レイアウト記述の配列
		戻り値: 頂点シェーダーのshared_ptr
		例外: 読み込みに失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::shared_ptr<VertexShader> CreateVertexShader(
		const std::wstring& filename
	);

	/*========================================================================================================
		ピクセルシェーダーの生成または取得
		
		ResourceManagerに登録されているピクセルシェーダーを取得する。
		登録されていない場合は、ファイルから読み込んでResourceManagerに登録する。
		ファイルパスには自動的に"shaders/cso/"を先頭に付加する。
		
		引数:
		  filename - シェーダーファイルのパス("shaders/cso/"は自動付加)
		戻り値: ピクセルシェーダーのshared_ptr
		例外: 読み込みに失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::shared_ptr<PixelShader> CreatePixelShader(
		const std::wstring& filename
	);

	/*========================================================================================================
		シェーダーリフレクションから入力レイアウトを自動生成
		
		シェーダーバイトコードからリフレクション情報を取得し、入力レイアウト記述を生成する。
		
		引数:
		  bytecode - シェーダーバイトコード
		戻り値: 生成された入力レイアウト記述の配列
		例外: 生成に失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::vector<D3D11_INPUT_ELEMENT_DESC> GenerateInputLayoutFromReflection(
		const std::vector<uint8_t>& bytecode
	);

private:
	// コンストラクタ削除(静的クラスとして使用)
	ShaderFactory() = delete;
	
	/*========================================================================================================
		ファイルパスに"shaders/cso/"プレフィックスを付加
		
		引数:
		  filename - 元のファイル名
		戻り値: プレフィックスが付加されたフルパス
	========================================================================================================*/
	static std::wstring BuildShaderPath(const std::wstring& filename);
	
	/*========================================================================================================
		シェーダーファイル(.cso)をID3D11Blobを使用して読み込む
		
		コンパイル済みシェーダーファイルをBlobとして読み込む。
		
		引数:
		  filename - シェーダーファイルのパス
		  blob - 読み込んだBlobを格納するComPtr
		例外: 読み込みに失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static void LoadShaderFile(const std::wstring& filename, Microsoft::WRL::ComPtr<ID3DBlob>& blob);
	
	/*========================================================================================================
		シェーダーのリフレクション情報を取得
		
		シェーダーのリフレクション情報を取得し、定数バッファ情報を抽出する。
		
		引数:
		  blob - シェーダーのBlob
		  shader - 定数バッファ情報を格納するShaderオブジェクト
		例外: リフレクションに失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static void ReflectShader(const Microsoft::WRL::ComPtr<ID3DBlob>& blob, Shader* shader);
};

#endif // SHADER_FACTORY_H
