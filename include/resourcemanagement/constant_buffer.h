/*============================================================================================================

    定数バッファクラス [constant_buffer.h]
    シェーダーの定数バッファを管理するクラス。
    バッファ名、変数名とオフセット値の組み合わせを保持する。
    DefaultバッファとDynamicバッファの2種類をサポートする。

    Author : Ryosuke Kageyama
    Date   : 2025/11/26

=============================================================================================================*/
#ifndef CONSTANT_BUFFER_H
#define CONSTANT_BUFFER_H

#include <d3d11.h>
#include <wrl/client.h>
#include <string>
#include <map>

/*============================================================================================================
    定数バッファの使用方法を示す列挙型
=============================================================================================================*/
enum class ConstantBufferUsage
{
    Default,    // デフォルトバッファ（CPU書き込み不可、GPU読み取り専用、UpdateSubresourceで更新）
    Dynamic     // ダイナミックバッファ（CPU書き込み可、GPU読み取り専用、Mapで更新）
};

/*============================================================================================================
    ConstantBufferクラス
    シェーダーの定数バッファを管理するクラス。
    バッファ名、サイズ、変数名とオフセット値の組み合わせを保持する。
=============================================================================================================*/
class ConstantBuffer
{
public:
    /*========================================================================================================
        コンストラクタ・デストラクタ
    ========================================================================================================*/
    
    // デフォルトコンストラクタ
    ConstantBuffer();
    
    // バッファ名とサイズを指定するコンストラクタ
    // 引数:
    //   name - バッファの名前
    //   size - バッファのサイズ（バイト）
    ConstantBuffer(const std::string& name, UINT size);
    
    // デストラクタ
    ~ConstantBuffer();

    /*========================================================================================================
        初期化・解放
    ========================================================================================================*/
    
    // 定数バッファを初期化する
    // 引数:
    //   name - バッファの名前
    //   size - バッファのサイズ（バイト）
    //   usage - バッファの使用方法（デフォルト: Dynamic）
    // 戻り値: 初期化に成功した場合true
    // 例外: 初期化に失敗した場合はruntime_errorをスロー
    bool Initialize(const std::string& name, UINT size, ConstantBufferUsage usage = ConstantBufferUsage::Dynamic);
    
    // 定数バッファを解放する
    void Release();

    /*========================================================================================================
        変数情報の管理
    ========================================================================================================*/
    
    // 変数情報を追加する
    // 引数:
    //   variableName - 変数の名前
    //   offset - バッファ内でのオフセット値（バイト）
    void AddVariable(const std::string& variableName, UINT offset);
    
    // 変数のオフセット値を取得する
    // 引数:
    //   variableName - 変数の名前
    // 戻り値: オフセット値（変数が存在しない場合は0）
    UINT GetVariableOffset(const std::string& variableName) const;
    
    // 変数が存在するか確認する
    // 引数:
    //   variableName - 変数の名前
    // 戻り値: 変数が存在する場合true
    bool HasVariable(const std::string& variableName) const;

    /*========================================================================================================
        ゲッター関数
    ========================================================================================================*/
    
    // バッファ名を取得する
    // 戻り値: バッファの名前
    const std::string& GetName() const;
    
    // バッファサイズを取得する
    // 戻り値: バッファのサイズ（バイト）
    UINT GetSize() const;
    
    // バッファオブジェクトを取得する
    // 戻り値: ID3D11Bufferのポインタ
    ID3D11Buffer* GetBuffer() const;
    
    // バインドスロット番号を取得する
    // 戻り値: バインドスロット番号
    UINT GetBindSlot() const;
    
    // バッファの使用方法を取得する
    // 戻り値: バッファの使用方法
    ConstantBufferUsage GetUsage() const;

    /*========================================================================================================
        セッター関数
    ========================================================================================================*/
    
    // バインドスロット番号を設定する
    // 引数:
    //   slot - バインドスロット番号
    void SetBindSlot(UINT slot);

    /*========================================================================================================
        バッファ操作
    ========================================================================================================*/
    
    // バッファを更新する
    // 引数:
    //   data - 更新するデータのポインタ
    // 例外: 更新に失敗した場合はruntime_errorをスロー
    void Update(const void* data);
    
    // 変数名を指定してバッファの一部を更新する
    // 引数:
    //   variableName - 更新する変数の名前
    //   data - 更新するデータのポインタ
    //   dataSize - データのサイズ（バイト）
    // 例外: 更新に失敗した場合はruntime_errorをスロー
    void UpdateVariable(const std::string& variableName, const void* data, UINT dataSize);

private:
    // バッファの名前
    std::string m_Name;
    
    // バッファのサイズ（バイト）
    UINT m_Size;
    
    // バインドスロット番号
    UINT m_BindSlot;
    
    // バッファの使用方法
    ConstantBufferUsage m_Usage;
    
    // バッファオブジェクト
    Microsoft::WRL::ComPtr<ID3D11Buffer> m_Buffer;
    
    // 変数名とオフセット値の組み合わせ
    std::map<std::string, UINT> m_Variables;
};

#endif // CONSTANT_BUFFER_H
