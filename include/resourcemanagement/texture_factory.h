/*============================================================================================================

    テクスチャファクトリー [texture_factory.h]
    Textureリソースの生成を管理するファクトリークラス。
    ResourceManagerと連携して、リソースの一元管理とキャッシュを実現する。

    Author : Ryosuke Kageyama
    Date   : 2025/11/26

=============================================================================================================*/
#ifndef TEXTURE_FACTORY_H
#define TEXTURE_FACTORY_H

#include <memory>
#include <string>

// 前方宣言
class Texture;

/*============================================================================================================
    TextureFactoryクラス
    Textureリソースの生成を管理するファクトリークラス。
    ResourceManagerに問い合わせ、キャッシュされていればそれを返し、
    なければファイルから読み込んでResourceManagerに登録する。
    ファイルパスには自動的に"resources/texture/"が先頭に付加される。
=============================================================================================================*/
class TextureFactory
{
public:
	/*========================================================================================================
		テクスチャの生成または取得
		
		ResourceManagerに登録されているテクスチャを取得する。
		登録されていない場合は、ファイルから読み込んでResourceManagerに登録する。
		ファイルパスには自動的に"resources/texture/"が先頭に付加される。
		
		引数:
		  filename - テクスチャファイルのパス（"resources/texture/"は自動付加）
		  generateMipMaps - ミップマップを生成するかどうか（デフォルト：true）
		戻り値: テクスチャのshared_ptr
		例外: 読み込みに失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::shared_ptr<Texture> Create(const std::wstring& filename, bool generateMipMaps = true);

private:
	// コンストラクタを削除（静的クラスとして使用）
	TextureFactory() = delete;
	
	/*========================================================================================================
		ファイルパスに"resources/texture/"プレフィックスを付加
		
		引数:
		  filename - 元のファイル名
		戻り値: プレフィックスが付加されたフルパス
	========================================================================================================*/
	static std::wstring BuildTexturePath(const std::wstring& filename);
};

#endif // TEXTURE_FACTORY_H
