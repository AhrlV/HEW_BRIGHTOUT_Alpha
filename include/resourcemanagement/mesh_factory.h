/*============================================================================================================

    メッシュファクトリー [mesh_factory.h]
    Meshリソースの生成を管理するファクトリークラス。
    ResourceManagerと連携して、リソースの一元管理とキャッシュを実現する。

    Author : Ryosuke Kageyama
    Date   : 2025/11/26

=============================================================================================================*/
#ifndef MESH_FACTORY_H
#define MESH_FACTORY_H

#include <memory>
#include <string>
#include <d3d11.h>

// 前方宣言
class Mesh;

/*============================================================================================================
    MeshFactoryクラス
    Meshリソースの生成を管理するファクトリークラス。
    ResourceManagerに問い合わせ、キャッシュされていればそれを返し、
    なければファイルから読み込んでResourceManagerに登録する。
=============================================================================================================*/
class MeshFactory
{
public:
	/*========================================================================================================
		メッシュの生成または取得
		
		ResourceManagerに登録されているメッシュを取得する。
		登録されていない場合は、ファイルから読み込んでResourceManagerに登録する。
		
		引数:
		  filename - メッシュファイルのパス
		戻り値: メッシュのshared_ptr
		例外: 読み込みに失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::shared_ptr<Mesh> Create(const std::wstring& filename);

	/*========================================================================================================
		立方体のプリミティブメッシュの生成または取得
		
		立方体のメッシュを生成または取得する。
		ResourceManagerにパラメータを含むキーで登録・キャッシュされる。
		
		引数:
		  size - 立方体の一辺のサイズ（デフォルト：1.0f）
		戻り値: 立方体のメッシュのshared_ptr
		例外: 生成に失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::shared_ptr<Mesh> CreateCube(float size = 1.0f);

	/*========================================================================================================
		球のプリミティブメッシュの生成または取得
		
		球のメッシュを生成または取得する。
		ResourceManagerにパラメータを含むキーで登録・キャッシュされる。
		
		引数:
		  radius - 球の半径（デフォルト：0.5f）
		  slices - 経度方向の分割数（デフォルト：32）
		  stacks - 緯度方向の分割数（デフォルト：32）
		戻り値: 球のメッシュのshared_ptr
		例外: 生成に失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::shared_ptr<Mesh> CreateSphere(float radius = 0.5f, int slices = 32, int stacks = 32);

	/*========================================================================================================
		円柱プリミティブメッシュの生成または取得
		
		円柱メッシュを生成または取得する。
		ResourceManagerにパラメータを含むキーで登録・キャッシュされる。
		
		引数:
		  radius - 円柱の半径（デフォルト：0.5f）
		  height - 円柱の高さ（デフォルト：1.0f）
		  slices - 円周方向の分割数（デフォルト：32）
		戻り値: 円柱メッシュのshared_ptr
		例外: 生成に失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::shared_ptr<Mesh> CreateCylinder(float radius = 0.5f, float height = 1.0f, int slices = 32);

	/*========================================================================================================
		カプセルプリミティブメッシュの生成または取得
		
		カプセルメッシュを生成または取得する。
		ResourceManagerにパラメータを含むキーで登録・キャッシュされる。
		
		引数:
		  radius - カプセルの半径（デフォルト：0.5f）
		  height - カプセルの円柱部分の高さ（デフォルト：1.0f）
		  slices - 円周方向の分割数（デフォルト：32）
		  stacks - 球の上下部分の分割数（デフォルト：16）
		戻り値: カプセルメッシュのshared_ptr
		例外: 生成に失敗した場合はruntime_errorをスロー
	========================================================================================================*/
	static std::shared_ptr<Mesh> CreateCapsule(float radius = 0.5f, float height = 1.0f, int slices = 32, int stacks = 16);

private:
	// コンストラクタを削除（静的クラスとして使用）
	MeshFactory() = delete;
};

#endif // MESH_FACTORY_H
