/*============================================================================================================

    リソースマネージャー [resource_manager.h]
    すべてのリソース（Mesh、Material、Textureなど）を一元管理するシングルトンクラス。
    ファイル名をキーとしてリソースを登録・取得できる。

    Author : Ryosuke Kageyama
    Date   : 2025/05/07

=============================================================================================================*/
#ifndef RESOURCEMANAGER_H
#define RESOURCEMANAGER_H

#include <string>
#include <unordered_map>
#include <memory>
#include "lifecycle/object.h"

/*============================================================================================================
    リソースマネージャークラス
    シングルトンパターンでリソースを一元管理する。
    各リソースはファイル名をキーとして管理され、重複読み込みを防ぐ。
=============================================================================================================*/
class ResourceManager
{
public:
    // コピーコンストラクタと代入演算子を削除（シングルトン）
    ResourceManager(const ResourceManager&) = delete;
    ResourceManager& operator=(const ResourceManager&) = delete;

    /*========================================================================================================
        シングルトンインスタンス取得
        戻り値: ResourceManagerの唯一のインスタンスへの参照
    ========================================================================================================*/
    static ResourceManager& Instance();

    /*========================================================================================================
        リソース登録
        新しいリソースをマネージャーに登録する。
        同一ファイル名のリソースが既に登録されている場合は登録しない。
        GameObjectとComponentは登録できない（StaticResourceBorderより後のクラスID）。
        
        引数:
          filename - リソースのファイル名（キーとして使用）
          resource - 登録するリソースのshared_ptr
        戻り値: 登録に成功した場合true、既に登録済みまたは無効なリソースの場合false
        例外: GameObjectまたはComponentを登録しようとした場合は例外をスロー
    ========================================================================================================*/
    bool RegisterResource(const std::wstring& filename, std::shared_ptr<Object> resource);

    /*========================================================================================================
        リソース取得
        指定したファイル名のリソースを取得する。
        リソースが存在しないか型が一致しない場合はnullptrを返す。
        
        引数:
          filename - 取得したいリソースのファイル名
        戻り値: 指定した型のリソースのshared_ptr（存在しない、または型が一致しない場合はnullptr）
    ========================================================================================================*/
    std::shared_ptr<Object> GetResource(const std::wstring& filename) const;

    /*========================================================================================================
        型指定リソース取得
        ファイル名と型を指定してリソースを取得する。
        型が一致しない場合はnullptrを返す。
        
        テンプレート引数:
          T - 取得したいリソースの型（ObjectまたはObject派生クラス）
        引数:
          filename - 取得したいリソースのファイル名
        戻り値: 指定した型のリソースのshared_ptr（存在しない、または型が一致しない場合はnullptr）
    ========================================================================================================*/
    template<typename T>
    std::shared_ptr<T> GetResource(const std::wstring& filename) const
    {
        auto resource = GetResource(filename);
        if (!resource)
        {
            return nullptr;
        }
        return std::dynamic_pointer_cast<T>(resource);
    }

    /*========================================================================================================
        リソース存在確認
        指定したファイル名のリソースが登録されているかを確認する。
        
        引数:
          filename - 確認するリソースのファイル名
        戻り値: リソースが存在する場合true、存在しない場合false
    ========================================================================================================*/
    bool HasResource(const std::wstring& filename) const;

    /*========================================================================================================
        リソース削除
        指定したファイル名のリソースをマネージャーから削除する。
        
        引数:
          filename - 削除するリソースのファイル名
        戻り値: 削除に成功した場合true、リソースが存在しなかった場合false
    ========================================================================================================*/
    bool RemoveResource(const std::wstring& filename);

    /*========================================================================================================
        クラスID指定リソース削除
        指定したクラスIDのリソースをすべて削除する。
        
        引数:
          classID - 削除するリソースのクラスID
        戻り値: 削除したリソース数
    ========================================================================================================*/
    size_t RemoveResourcesByClassID(ResourceClassID classID);

    /*========================================================================================================
        全リソース削除
        登録されているすべてのリソースをマネージャーから削除する。
    ========================================================================================================*/
    void Clear();

    /*========================================================================================================
        総リソース数取得
        登録されているリソースの総数を取得する。
        
        戻り値: 登録されているリソースの総数
    ========================================================================================================*/
    size_t GetResourceCount() const;

    /*========================================================================================================
        クラスID指定リソース数取得
        指定したクラスIDのリソース数を取得する。
        
        引数:
          classID - カウントするリソースのクラスID
        戻り値: 指定したクラスIDのリソース数
    ========================================================================================================*/
    size_t GetResourceCountByClassID(ResourceClassID classID) const;

    /*========================================================================================================
        デバッグ出力
        登録されているすべてのリソースの情報をデバッグ出力する。
    ========================================================================================================*/
    void DumpResourceInfo() const;

private:
    // プライベートコンストラクタ（シングルトン）
    ResourceManager() = default;
    
    // デストラクタ（すべてのリソースを解放）
    ~ResourceManager();

    // ファイル名とリソースを紐付けるマップ
    std::unordered_map<std::wstring, std::shared_ptr<Object>> m_Resources;
};
#endif
