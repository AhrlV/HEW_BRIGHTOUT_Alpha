/*============================================================================================================

    テクスチャクラス [texture.h]
    テクスチャリソースを管理するクラス。
    DirectXTexライブラリを使用してテクスチャを読み込み、シェーダーリソースビューを保持する。

    Author : Ryosuke Kageyama
    Date   : 2025/05/07

=============================================================================================================*/

#ifndef TEXTURE_H
#define TEXTURE_H

#include <d3d11.h>
#include <wrl/client.h>
#include <DirectXMath.h>
#include "lifecycle/object.h"

/*============================================================================================================
    テクスチャクラス
    テクスチャファイルを読み込み、シェーダーリソースビューとして管理する。
    Objectクラスを継承し、ResourceManagerによる一元管理が可能。
=============================================================================================================*/
class Texture : public Object
{
public:
    // デフォルトコンストラクタ
    Texture();
    
    // 識別名を指定するコンストラクタ
    // 引数:
    //   name - このテクスチャの識別名（ファイル名やキャッシュキーなど）
    explicit Texture(const std::wstring& name);
    
    // デストラクタ
    ~Texture() override;

    /*========================================================================================================
        テクスチャの初期化と読み込み
        指定したファイルからテクスチャを読み込み、シェーダーリソースビューを作成する。
        
        引数:
          filename - 読み込むテクスチャファイルのパス
          generateMipMaps - ミップマップを生成するかどうか（デフォルトはtrue）
        戻り値: 初期化に成功した場合true、失敗した場合はruntime_error例外をスロー
    ========================================================================================================*/
    bool Initialize(const std::wstring& filename, bool generateMipMaps = true);
    
    /*========================================================================================================
        テクスチャデータを直接設定する（Factoryからの使用を想定）
        
        引数:
          srv - シェーダーリソースビュー
          width - テクスチャの幅
          height - テクスチャの高さ
    ========================================================================================================*/
    void SetTextureData(Microsoft::WRL::ComPtr<ID3D11ShaderResourceView> srv, unsigned int width, unsigned int height);

    /*========================================================================================================
        シェーダーへのテクスチャ設定
        このテクスチャをピクセルシェーダーのスロット0に設定する。
        
        引数:
          context - Direct3D11デバイスコンテキスト
          slot - シェーダーリソーススロット番号（デフォルトは0）
    ========================================================================================================*/
    void SetToShader(UINT slot = 0) const;

    /*========================================================================================================
        リソース管理
    ========================================================================================================*/
    
    // リソースを解放する
    void Release();
    
    // リソースが有効かどうかを判定する
    // 戻り値: シェーダーリソースビューが有効な場合true
    bool IsValid() const;

    /*========================================================================================================
        ゲッター関数群
    ========================================================================================================*/
    
    // シェーダーリソースビューを取得する
    // 戻り値: シェーダーリソースビューのポインタ
    ID3D11ShaderResourceView* GetShaderResourceView() const;
    
    // テクスチャの幅を取得する
    // 戻り値: テクスチャの幅（ピクセル）
    unsigned int GetWidth() const;
    
    // テクスチャの高さを取得する
    // 戻り値: テクスチャの高さ（ピクセル）
    unsigned int GetHeight() const;
    
    // テクスチャのサイズを取得する
    // 戻り値: テクスチャのサイズ（幅と高さ）
    DirectX::XMUINT2 GetSize() const;


private:
    // シェーダーリソースビュー（テクスチャをシェーダーで使用するためのビュー）
    Microsoft::WRL::ComPtr<ID3D11ShaderResourceView> m_ShaderResourceView;
    
    // テクスチャの幅（ピクセル）
    unsigned int m_Width;
    
    // テクスチャの高さ（ピクセル）
    unsigned int m_Height;
};

#endif