/*============================================================================================================

    メッシュクラス [mesh.h]
    3Dモデルの頂点データとインデックスデータを管理するクラス。
    頂点バッファとインデックスバッファを保持し、描画に必要な情報を提供する。

    Author : Ryosuke Kageyama
    Date   : 2025/05/07
    Date   : 2025/11/25

=============================================================================================================*/
#ifndef MESH_H
#define MESH_H

#include <d3d11.h>
#include <wrl/client.h>
#include <vector>
#include <memory>
#include <DirectXMath.h>
#include "lifecycle/object.h"

// 前方宣言
class VertexShader;

/*============================================================================================================
    メッシュ頂点構造体
    メッシュの各頂点が持つ情報を定義する。
=============================================================================================================*/
struct MeshVertex
{
    DirectX::XMFLOAT4 position;     // 位置
    DirectX::XMFLOAT3 normal;       // 法線
    DirectX::XMFLOAT2 texcoord;     // uv
    DirectX::XMFLOAT4 color;        // 頂点カラー
};

/*============================================================================================================
    メッシュクラス
    3Dモデルの頂点データとインデックスデータを管理する。
    Objectクラスを継承し、ResourceManagerによる一元管理が可能。
=============================================================================================================*/
class Mesh : public Object
{
public:
	// デフォルトコンストラクタ
	Mesh();
	
	// 識別名を指定するコンストラクタ
	// 引数:
	//   name - このメッシュの識別名（ファイル名やキャッシュキーなど）
	explicit Mesh(const std::wstring& name);
	
	// デストラクタ
	~Mesh() override;

	/*========================================================================================================
	    メッシュの初期化
	    頂点データとインデックスデータから頂点バッファとインデックスバッファを作成する。
	    
	    引数:
	      vertices - 頂点データの配列
	      indices - インデックスデータの配列
	    戻り値: 初期化に成功した場合true
	    例外: 初期化に失敗した場合はruntime_error例外をスロー
	========================================================================================================*/
	bool Initialize(const std::vector<MeshVertex>& vertices, const std::vector<uint32_t>& indices);

	/*========================================================================================================
	    リソース管理
	========================================================================================================*/
	
	// リソースを解放する
	void Release();
	
	// リソースが有効かどうかを判定する
	// 戻り値: 頂点バッファとインデックスバッファが有効な場合true
	bool IsValid() const;

	/*========================================================================================================
	    ゲッター関数群
	========================================================================================================*/
	
	// 頂点バッファを取得する
	// 戻り値: 頂点バッファのポインタ
	ID3D11Buffer* GetVertexBuffer() const;
	
	// インデックスバッファを取得する
	// 戻り値: インデックスバッファのポインタ
	ID3D11Buffer* GetIndexBuffer() const;
	
	// インデックス数を取得する
	// 戻り値: インデックスの総数
	UINT GetIndexCount() const;
	
	// プリミティブトポロジーを取得する
	// 戻り値: プリミティブトポロジー（三角形リストなど）
	D3D11_PRIMITIVE_TOPOLOGY GetTopology() const;
	
	// 頂点シェーダーを取得する
	// 戻り値: 頂点シェーダーのshared_ptr
	std::shared_ptr<VertexShader> GetVertexShader() const;

	/*========================================================================================================
	    セッター関数群
	========================================================================================================*/
	
	// プリミティブトポロジーを設定する
	// 引数:
	//   topo - 設定するプリミティブトポロジー
	void SetTopology(D3D11_PRIMITIVE_TOPOLOGY topo);
	
	// 頂点シェーダーを設定する
	// 引数:
	//   vs - 設定する頂点シェーダーのshared_ptr
	void SetVertexShader(std::shared_ptr<VertexShader> vs);

	/*========================================================================================================
	    シェーダー定数バッファ更新
	========================================================================================================*/
	
	// 頂点シェーダーのPerObject定数バッファを更新する
	// ワールド行列をシェーダーに送信する。
	// 引数:
	//   worldMatrix - ワールド変換行列
	//   vertexShader - 更新対象の頂点シェーダー
	// 例外: 更新に失敗した場合はruntime_errorをスロー
	void UpdateVertexShaderPerObject(const DirectX::XMMATRIX& worldMatrix, VertexShader* vertexShader) const;

private:
	// 頂点バッファ
	Microsoft::WRL::ComPtr<ID3D11Buffer> m_VertexBuffer;
	
	// インデックスバッファ
	Microsoft::WRL::ComPtr<ID3D11Buffer> m_IndexBuffer;
	
	// インデックス数
	UINT m_IndexCount;
	
	// プリミティブトポロジー（描画時の頂点の解釈方法）
	D3D11_PRIMITIVE_TOPOLOGY m_Topology;
	
	// 頂点シェーダー（このメッシュ専用）
	std::shared_ptr<VertexShader> m_VertexShader;
};

#endif // MESH_H
