/*============================================================================================================

    メッシュレンダラークラス [mesh_renderer.h]
    メッシュとマテリアルを組み合わせて3Dモデルを描画するコンポーネント。
    頂点シェーダーはメッシュが保持し、ピクセルシェーダーはマテリアルが保持する。

    Author : Ryosuke Kageyama
    Date   : 2025/11/26

=============================================================================================================*/
#ifndef DIRECT3D_MESHRENDERER_H
#define DIRECT3D_MESHRENDERER_H


#include <d3d11.h>
#include <memory>
#include "direct3D/mesh.h"
#include "direct3D/material.h"
#include "direct3D/shader.h"
#include "lifecycle/component.h"
#include "lifecycle/camera.h"
#include "physics/transform.h"

/*============================================================================================================
    メッシュレンダラークラス
    メッシュとマテリアルを組み合わせて3Dモデルを描画するコンポーネント。
    頂点シェーダーはメッシュが保持し、ピクセルシェーダーはマテリアルが保持する。
=============================================================================================================*/
class MeshRenderer : public Component
{
public:
    /*========================================================================================================
        コンストラクタ・デストラクタ
    ========================================================================================================*/
    
    // デフォルトコンストラクタ
    MeshRenderer();
    
    // デストラクタ
    ~MeshRenderer();

    /*========================================================================================================
        初期化・更新・描画
    ========================================================================================================*/
    
    // コンポーネント初期化（TransFormコンポーネントの参照を取得）
    void Awake() override;
    
    // 描画処理
    // 引数:
    //   camera - カメラの参照（ビュー行列とプロジェクション行列を取得）
    void Render(const Camera& camera);

    /*========================================================================================================
        セッター関数群
    ========================================================================================================*/
    
    // メッシュを設定する
    // 引数:
    //   mesh - 設定するメッシュのshared_ptr
    void SetMesh(std::shared_ptr<Mesh> mesh);
    
    // マテリアルを設定する
    // 引数:
    //   mat - 設定するマテリアルのshared_ptr
    void SetMaterial(std::shared_ptr<Material> mat);

    /*========================================================================================================
        ゲッター関数群
    ========================================================================================================*/
    
    // メッシュを取得する
    // 戻り値: メッシュのshared_ptr
    std::shared_ptr<Mesh> GetMesh() const;
    
    // マテリアルを取得する
    // 戻り値: マテリアルのshared_ptr
    std::shared_ptr<Material> GetMaterial() const;

private:
    /*========================================================================================================
        内部描画処理
    ========================================================================================================*/
    
    // 頂点シェーダーを設定する
    // 引数:
    //   vertexShader - 頂点シェーダーのポインタ
    //   camera - カメラの参照
    void SetupVertexShader(VertexShader* vertexShader, const Camera& camera);
    
    // ピクセルシェーダーを設定する
    // 引数:
    //   pixelShader - ピクセルシェーダーのポインタ
    void SetupPixelShader(PixelShader* pixelShader);
    
    // レンダリングステートを設定する
    void SetupRenderStates();
    
    // メッシュバッファを設定して描画する
    void DrawMesh();

    /*========================================================================================================
        メンバ変数
    ========================================================================================================*/
    
    // メッシュ（頂点データとインデックスデータ、頂点シェーダーを保持）
    std::shared_ptr<Mesh> m_Mesh;
    
    // マテリアル（質感とピクセルシェーダーを保持）
    std::shared_ptr<Material> m_Material;
};
#endif
