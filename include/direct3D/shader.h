/*============================================================================================================

    シェーダークラス [shader.h]
    頂点シェーダーとピクセルシェーダーの基底クラス。
    Resourceクラスを継承し、ResourceManagerによる一元管理が可能。
    シェーダーファイル（.cso）の読み込みと、定数バッファの管理を行う。

    Author : Ryosuke Kageyama
    Date   : 2025/11/25

=============================================================================================================*/
#ifndef SHADER_H
#define SHADER_H

#include <d3d11.h>
#include <wrl/client.h>
#include <string>
#include <vector>
#include <map>
#include <memory>
#include "direct3D/resource.h"

// 前方宣言
class ConstantBuffer;

/*============================================================================================================
    シェーダータイプ列挙型
    シェーダーの種類を識別するための列挙型
=============================================================================================================*/
enum class ShaderType
{
    Vertex,     // 頂点シェーダー
    Pixel,      // ピクセルシェーダー
    Geometry,   // ジオメトリシェーダー（将来拡張用）
    Compute,    // コンピュートシェーダー（将来拡張用）
    Hull,       // ハルシェーダー（将来拡張用）
    Domain,     // ドメインシェーダー（将来拡張用）
    Unknown     // 不明なシェーダータイプ
};

/*============================================================================================================
    シェーダー基底クラス
    すべてのシェーダーの基底クラス。
    Resourceクラスを継承し、ResourceManagerによる一元管理が可能。
=============================================================================================================*/
class Shader : public Resource
{
public:
    /*========================================================================================================
        コンストラクタ・デストラクタ
    ========================================================================================================*/
    
    // デフォルトコンストラクタ
    Shader();
    
    // シェーダータイプを指定するコンストラクタ
    // 引数:
    //   type - シェーダーのタイプ（Vertex, Pixelなど）
    Shader(ShaderType type);
    
    // 識別名とシェーダータイプを指定するコンストラクタ
    // 引数:
    //   name - このシェーダーの識別名
    //   type - シェーダーのタイプ
    Shader(const std::wstring& name, ShaderType type);
    
    // デストラクタ
    virtual ~Shader() override;

    /*========================================================================================================
        定数バッファ管理
    ========================================================================================================*/
    
    // 定数バッファを追加する
    // 引数:
    //   device - Direct3D11デバイス
    //   byteWidth - 定数バッファのサイズ（バイト）
    // 戻り値: 追加された定数バッファのインデックス
    // 例外: 作成に失敗した場合はruntime_errorをスロー
    size_t AddConstantBuffer(UINT byteWidth);
    
    // 定数バッファを取得する
    // 引数:
    //   index - 定数バッファのインデックス
    // 戻り値: 定数バッファのポインタ（存在しない場合はnullptr）
    ID3D11Buffer* GetConstantBuffer(size_t index) const;
    
    // 定数バッファ数を取得する
    // 戻り値: 定数バッファの総数
    size_t GetConstantBufferCount() const;
    
    // 定数バッファを更新する
    // 引数:
    //   index - 定数バッファのインデックス
    //   data - 更新するデータのポインタ
    // 例外: 更新に失敗した場合はruntime_errorをスロー
    void UpdateConstantBuffer(size_t index, const void* data);
    
    // 定数バッファ情報を名前で取得する
    // 引数:
    //   name - 定数バッファの名前
    // 戻り値: ConstantBufferのポインタ（存在しない場合はnullptr）
    ConstantBuffer* GetConstantBufferByName(const std::string& name);
    
    // 定数バッファ情報を追加する
    // 引数:
    //   name - 定数バッファの名前
    //   constantBuffer - ConstantBufferのshared_ptr
    void AddConstantBufferInfo(const std::string& name, std::shared_ptr<ConstantBuffer> constantBuffer);

    /*========================================================================================================
        シェーダー設定（純粋仮想関数）
    ========================================================================================================*/
    
    // シェーダーをパイプラインに設定する（派生クラスで実装）
    // 引数:
    // 例外: 設定に失敗した場合はruntime_error例外をスロー
    virtual void SetToContext() = 0;
    
    // 定数バッファをシェーダーに設定する（派生クラスで実装）
    // 引数:
    //   startSlot - 開始スロット番号
    virtual void SetConstantBuffers(UINT startSlot = 0) = 0;

    /*========================================================================================================
        Resource基底クラスのオーバーライド
    ========================================================================================================*/
    
    // リソースを解放する
    void Release() override;
    
    // リソースが有効かどうかを判定する（派生クラスで実装）
    // 戻り値: シェーダーが有効な場合true
    virtual bool IsValid() const override = 0;

    /*========================================================================================================
        ゲッター関数群
    ========================================================================================================*/
    
    // シェーダータイプを取得する
    // 戻り値: シェーダーのタイプ
    ShaderType GetShaderType() const;
    
    // シェーダーバイトコードを取得する
    // 戻り値: シェーダーバイトコード
    const std::vector<uint8_t>& GetBytecode() const;

protected:
    /*========================================================================================================
        内部ヘルパー関数
    ========================================================================================================*/
    
    // シェーダーファイル（.cso）を読み込む
    // 引数:
    //   filename - シェーダーファイルのパス
    //   bytecode - 読み込んだバイトコードを格納するベクター
    // 例外: 読み込みに失敗した場合はruntime_error例外をスロー
    void LoadShaderFile(const std::wstring& filename, std::vector<uint8_t>& bytecode);

    /*========================================================================================================
        メンバ変数
    ========================================================================================================*/
    
    // シェーダーのタイプ
    ShaderType m_ShaderType;
    
    // 定数バッファのリスト
    std::vector<Microsoft::WRL::ComPtr<ID3D11Buffer>> m_ConstantBuffers;
    
    // シェーダーバイトコード
    std::vector<uint8_t> m_Bytecode;
    
    // 定数バッファ名とConstantBufferクラスのマップ
    std::map<std::string, std::shared_ptr<ConstantBuffer>> m_ConstantBufferMap;
};

/*============================================================================================================
    頂点シェーダークラス
    頂点シェーダーを管理する派生クラス。
    入力レイアウトの管理も行う。
=============================================================================================================*/
class VertexShader : public Shader
{
public:
    /*========================================================================================================
        コンストラクタ・デストラクタ
    ========================================================================================================*/
    
    // デフォルトコンストラクタ
    VertexShader();
    
    // 識別名を指定するコンストラクタ
    // 引数:
    //   name - この頂点シェーダーの識別名
    explicit VertexShader(const std::wstring& name);
    
    // デストラクタ
    ~VertexShader() override;

    /*========================================================================================================
        初期化関数
    ========================================================================================================*/
    
    // 頂点シェーダーとして初期化
    // 引数:
    //   filename - シェーダーファイルのパス（.csoファイル）
    //   inputLayout - 入力レイアウト記述の配列
    // 戻り値: 初期化に成功した場合true
    // 例外: 初期化に失敗した場合はruntime_error例外をスロー
    bool Initialize(
        const std::wstring& filename,
        const std::vector<D3D11_INPUT_ELEMENT_DESC>& inputLayout
    );

    /*========================================================================================================
        Shaderクラスのオーバーライド
    ========================================================================================================*/
    
    // シェーダーをパイプラインに設定する
    // 引数:
    // 例外: 設定に失敗した場合はruntime_error例外をスロー
    void SetToContext() override;
    
    // 定数バッファをシェーダーに設定する
    // 引数:
    //   context - Direct3D11デバイスコンテキスト
    //   startSlot - 開始スロット番号
    void SetConstantBuffers(UINT startSlot = 0) override;
    
    // リソースが有効かどうかを判定する
    // 戻り値: 頂点シェーダーが有効な場合true
    bool IsValid() const override;

    /*========================================================================================================
        ゲッター関数群
    ========================================================================================================*/
    
    // 頂点シェーダーを取得する
    // 戻り値: 頂点シェーダーのポインタ
    ID3D11VertexShader* GetVertexShader() const;
    
    // 入力レイアウトを取得する
    // 戻り値: 入力レイアウトのポインタ
    ID3D11InputLayout* GetInputLayout() const;

private:
    // 頂点シェーダー
    Microsoft::WRL::ComPtr<ID3D11VertexShader> m_VertexShader;
    
    // 入力レイアウト
    Microsoft::WRL::ComPtr<ID3D11InputLayout> m_InputLayout;
};

/*============================================================================================================
    ピクセルシェーダークラス
    ピクセルシェーダーを管理する派生クラス。
=============================================================================================================*/
class PixelShader : public Shader
{
public:
    /*========================================================================================================
        コンストラクタ・デストラクタ
    ========================================================================================================*/
    
    // デフォルトコンストラクタ
    PixelShader();
    
    // 識別名を指定するコンストラクタ
    // 引数:
    //   name - このピクセルシェーダーの識別名
    explicit PixelShader(const std::wstring& name);
    
    // デストラクタ
    ~PixelShader() override;

    /*========================================================================================================
        初期化関数
    ========================================================================================================*/
    
    // ピクセルシェーダーとして初期化
    // 引数:
    //   device - Direct3D11デバイス
    //   filename - シェーダーファイルのパス（.csoファイル）
    // 戻り値: 初期化に成功した場合true
    // 例外: 初期化に失敗した場合はruntime_error例外をスロー
    bool Initialize(
        const std::wstring& filename
    );

    /*========================================================================================================
        Shaderクラスのオーバーライド
    ========================================================================================================*/
    
    // シェーダーをパイプラインに設定する
    // 引数:
    // 例外: 設定に失敗した場合はruntime_error例外をスロー
    void SetToContext() override;
    
    // 定数バッファをシェーダーに設定する
    // 引数:
    //   startSlot - 開始スロット番号
    void SetConstantBuffers(UINT startSlot = 0) override;
    
    // リソースが有効かどうかを判定する
    // 戻り値: ピクセルシェーダーが有効な場合true
    bool IsValid() const override;

    /*========================================================================================================
        ゲッター関数群
    ========================================================================================================*/
    
    // ピクセルシェーダーを取得する
    // 戻り値: ピクセルシェーダーのポインタ
    ID3D11PixelShader* GetPixelShader() const;

private:
    // ピクセルシェーダー
    Microsoft::WRL::ComPtr<ID3D11PixelShader> m_PixelShader;
};

#endif // SHADER_H
