/*============================================================================================================

    プロパティブロック基底クラス [property_block.h]
    シェーダーのプロパティ値を一時的にオーバーライドするための基底クラス。
    汎用的なプロパティ管理機能を提供する。

    Author : Ryosuke Kageyama
    Date   : 2025/11/26

=============================================================================================================*/
#ifndef PROPERTY_BLOCK_H
#define PROPERTY_BLOCK_H

#include <DirectXMath.h>
#include <map>
#include <string>
#include <variant>
#include <vector>

/*============================================================================================================
    プロパティブロック基底クラス
    シェーダーのプロパティ値を一時的にオーバーライドする汎用クラス。
=============================================================================================================*/
class PropertyBlock
{
public:
    /*========================================================================================================
        コンストラクタ・デストラクタ
    ========================================================================================================*/
    
    // デフォルトコンストラクタ
    PropertyBlock();
    
    // 仮想デストラクタ
    virtual ~PropertyBlock();

    /*========================================================================================================
        プロパティ設定
    ========================================================================================================*/
    
    // Float4プロパティを設定する
    // 引数:
    //   name - プロパティ名
    //   value - 設定する値
    void SetFloat4(const std::string& name, const DirectX::XMFLOAT4& value);
    
    // Float3プロパティを設定する
    // 引数:
    //   name - プロパティ名
    //   value - 設定する値
    void SetFloat3(const std::string& name, const DirectX::XMFLOAT3& value);
    
    // Floatプロパティを設定する
    // 引数:
    //   name - プロパティ名
    //   value - 設定する値
    void SetFloat(const std::string& name, float value);

    /*========================================================================================================
        プロパティ取得
    ========================================================================================================*/
    
    // Float4プロパティを取得する
    // 引数:
    //   name - プロパティ名
    //   value - 取得した値を格納する変数
    // 戻り値: プロパティが存在する場合true
    bool GetFloat4(const std::string& name, DirectX::XMFLOAT4& value) const;
    
    // Float3プロパティを取得する
    // 引数:
    //   name - プロパティ名
    //   value - 取得した値を格納する変数
    // 戻り値: プロパティが存在する場合true
    bool GetFloat3(const std::string& name, DirectX::XMFLOAT3& value) const;
    
    // Floatプロパティを取得する
    // 引数:
    //   name - プロパティ名
    //   value - 取得した値を格納する変数
    // 戻り値: プロパティが存在する場合true
    bool GetFloat(const std::string& name, float& value) const;

    /*========================================================================================================
        プロパティ管理
    ========================================================================================================*/
    
    // プロパティが存在するか確認する
    // 引数:
    //   name - プロパティ名
    // 戻り値: プロパティが存在する場合true
    bool HasProperty(const std::string& name) const;
    
    // すべてのプロパティをクリアする
    void Clear();
    
    // プロパティが空かどうかを確認する
    // 戻り値: プロパティが一つも設定されていない場合true
    bool IsEmpty() const;
    
    // すべてのプロパティ名を取得する
    // 戻り値: プロパティ名のリスト
    std::vector<std::string> GetPropertyNames() const;

protected:
    /*========================================================================================================
        内部データ型
    ========================================================================================================*/
    
    // プロパティデータ（std::variantを使用）
    using PropertyData = std::variant<float, DirectX::XMFLOAT3, DirectX::XMFLOAT4>;

    /*========================================================================================================
        メンバ変数
    ========================================================================================================*/
    
    // プロパティマップ
    std::map<std::string, PropertyData> m_Properties;
};

#endif // PROPERTY_BLOCK_H
