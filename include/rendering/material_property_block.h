/*============================================================================================================

    マテリアルプロパティブロッククラス [material_property_block.h]
    マテリアルのプロパティ値を一時的にオーバーライドするためのクラス。
    MeshRenderer単位でマテリアルの値を変更する際に使用する。
    PropertyBlock基底クラスを継承し、マテリアル専用の便利関数を提供する。

    Author : Ryosuke Kageyama
    Date   : 2025/11/26

=============================================================================================================*/
#ifndef MATERIAL_PROPERTY_BLOCK_H
#define MATERIAL_PROPERTY_BLOCK_H

#include "rendering/property_block.h"
#include <DirectXMath.h>
#include <memory>

// 前方宣言
class Texture;

/*============================================================================================================
    マテリアルプロパティブロッククラス
    マテリアルのプロパティ値を一時的にオーバーライドする。
    デフォルトシェーダーの定数バッファ名に対応した便利関数を提供する。
    テクスチャリソースの設定も可能。
=============================================================================================================*/
class MaterialPropertyBlock : public PropertyBlock
{
public:
    /*========================================================================================================
        コンストラクタ・デストラクタ
    ========================================================================================================*/
    
    // デフォルトコンストラクタ
    MaterialPropertyBlock();
    
    // デストラクタ
    ~MaterialPropertyBlock() override;

    /*========================================================================================================
        マテリアル専用プロパティ設定関数
        デフォルトシェーダーの定数バッファ変数名に直接対応
    ========================================================================================================*/
    
    // 基本カラーを設定する
    // シェーダーの"base_color"変数に書き込む
    // 引数:
    //   color - 基本カラー（RGBA）
    void SetBaseColor(const DirectX::XMFLOAT4& color);
    
    // 拡散反射色を設定する
    // シェーダーの"diffuse_color"変数に書き込む
    // 引数:
    //   color - 拡散反射色（RGBA）
    void SetDiffuseColor(const DirectX::XMFLOAT4& color);
    
    // 環境光色を設定する
    // シェーダーの"ambient_color"変数に書き込む
    // 引数:
    //   color - 環境光色（RGBA）
    void SetAmbientColor(const DirectX::XMFLOAT4& color);
    
    // 鏡面反射色を設定する
    // シェーダーの"specular_color"変数に書き込む
    // 引数:
    //   color - 鏡面反射色（RGBA）
    void SetSpecularColor(const DirectX::XMFLOAT4& color);
    
    // 放射色を設定する
    // シェーダーの"emissive_color"変数に書き込む
    // 引数:
    //   color - 放射色（RGBA）
    void SetEmissiveColor(const DirectX::XMFLOAT4& color);

    /*========================================================================================================
        マテリアル専用プロパティ取得関数
    ========================================================================================================*/
    
    // 基本カラーを取得する
    // 引数:
    //   color - 取得した値を格納する変数
    // 戻り値: プロパティが存在する場合true
    bool GetBaseColor(DirectX::XMFLOAT4& color) const;
    
    // 拡散反射色を取得する
    // 引数:
    //   color - 取得した値を格納する変数
    // 戻り値: プロパティが存在する場合true
    bool GetDiffuseColor(DirectX::XMFLOAT4& color) const;
    
    // 環境光色を取得する
    // 引数:
    //   color - 取得した値を格納する変数
    // 戻り値: プロパティが存在する場合true
    bool GetAmbientColor(DirectX::XMFLOAT4& color) const;
    
    // 鏡面反射色を取得する
    // 引数:
    //   color - 取得した値を格納する変数
    // 戻り値: プロパティが存在する場合true
    bool GetSpecularColor(DirectX::XMFLOAT4& color) const;
    
    // 放射色を取得する
    // 引数:
    //   color - 取得した値を格納する変数
    // 戻り値: プロパティが存在する場合true
    bool GetEmissiveColor(DirectX::XMFLOAT4& color) const;

    /*========================================================================================================
        テクスチャ管理
    ========================================================================================================*/
    
    // テクスチャを設定する
    // マテリアルのテクスチャをオーバーライドする
    // 引数:
    //   texture - 設定するテクスチャのshared_ptr
    void SetTexture(std::shared_ptr<Texture> texture);
    
    // テクスチャを取得する
    // 戻り値: 設定されているテクスチャのshared_ptr（設定されていない場合はnullptr）
    std::shared_ptr<Texture> GetTexture() const;
    
    // テクスチャが設定されているか確認する
    // 戻り値: テクスチャが設定されている場合true
    bool HasTexture() const;
    
    // テクスチャをクリアする
    // 設定されているテクスチャを解除する
    void ClearTexture();

private:
    /*========================================================================================================
        メンバ変数
    ========================================================================================================*/
    
    // オーバーライド用テクスチャ
    std::shared_ptr<Texture> m_OverrideTexture;
};

#endif // MATERIAL_PROPERTY_BLOCK_H
