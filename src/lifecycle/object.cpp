#include "lifecycle/object.h"

/*====================================================================
	デフォルトコンストラクタ
	メンバ変数を初期化する。
====================================================================*/
Object::Object()
	: m_Id(0)
	, m_Active(true)
	, m_Destroy(false)
	, m_ClassID(ResourceClassID::Unknown)
	, m_Name(L"")
{
}

/*====================================================================
	デストラクタ
	リソースを解放する。
====================================================================*/
Object::~Object()
{
}

/*====================================================================
	IDを取得する
	戻り値: シーン内での一意なID
====================================================================*/
uint64_t Object::GetId() const
{
	return m_Id;
}

/*====================================================================
	アクティブ状態を取得する
	戻り値: アクティブな場合true
====================================================================*/
bool Object::IsActive() const
{
	return m_Active;
}

/*====================================================================
	アクティブ状態を設定する
	引数:
	  active - 設定するアクティブ状態
====================================================================*/
void Object::SetActive(bool active)
{
	m_Active = active;
}

/*====================================================================
	破棄予約状態を取得する
	戻り値: 破棄予約されている場合true
====================================================================*/
bool Object::IsDestroyed() const
{
	return m_Destroy;
}

/*====================================================================
	オブジェクトを破棄予約する
	次のフレームの更新終了時に削除される。
====================================================================*/
void Object::Destroy()
{
	m_Destroy = true;
}

/*====================================================================
	クラスIDを取得する
	戻り値: オブジェクトのクラスID（ResourceClassID列挙型）
====================================================================*/
ResourceClassID Object::GetClassID() const
{
	return m_ClassID;
}

/*====================================================================
	クラスIDを設定する
	引数:
	  classID - 設定するクラスID（ResourceClassID列挙型）
====================================================================*/
void Object::SetClassID(ResourceClassID classID)
{
	m_ClassID = classID;
}

/*====================================================================
	識別名を取得する
	戻り値: オブジェクトの識別名
====================================================================*/
const std::wstring& Object::GetName() const
{
	return m_Name;
}

/*====================================================================
	識別名を設定する
	引数:
	  name - 設定する識別名
====================================================================*/
void Object::SetName(const std::wstring& name)
{
	m_Name = name;
}
