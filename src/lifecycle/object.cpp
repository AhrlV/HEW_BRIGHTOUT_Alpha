#include "lifecycle/object.h"

/*====================================================================
	デフォルトコンストラクタ
	メンバ変数を初期化する。
====================================================================*/
Object::Object()
	: m_Id(0)
	, m_Active(true)
	, m_Destroy(false)
{
}

/*====================================================================
	デストラクタ
	リソースを解放する。
====================================================================*/
Object::~Object()
{
}

/*====================================================================
	IDを取得する
	戻り値: シーン内での一意なID
====================================================================*/
uint64_t Object::GetId() const
{
	return m_Id;
}

/*====================================================================
	アクティブ状態を取得する
	戻り値: アクティブな場合true
====================================================================*/
bool Object::IsActive() const
{
	return m_Active;
}

/*====================================================================
	アクティブ状態を設定する
	引数:
	  active - 設定するアクティブ状態
====================================================================*/
void Object::SetActive(bool active)
{
	m_Active = active;
}

/*====================================================================
	破棄予約状態を取得する
	戻り値: 破棄予約されている場合true
====================================================================*/
bool Object::IsDestroyed() const
{
	return m_Destroy;
}

/*====================================================================
	オブジェクトを破棄予約する
	次のフレームの更新終了時に削除される。
====================================================================*/
void Object::Destroy()
{
	m_Destroy = true;
}
