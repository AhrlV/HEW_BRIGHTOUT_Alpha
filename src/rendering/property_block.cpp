#include "rendering/property_block.h"
#include <algorithm>

/*============================================================================================================
    デフォルトコンストラクタ
    メンバ変数を初期化する。
=============================================================================================================*/
PropertyBlock::PropertyBlock()
{
}

/*============================================================================================================
    仮想デストラクタ
=============================================================================================================*/
PropertyBlock::~PropertyBlock()
{
}

/*============================================================================================================
    Float4プロパティを設定する
    引数:
      name - プロパティ名
      value - 設定する値
=============================================================================================================*/
void PropertyBlock::SetFloat4(const std::string& name, const DirectX::XMFLOAT4& value)
{
    m_Properties[name] = value;
}

/*============================================================================================================
    Float3プロパティを設定する
    引数:
      name - プロパティ名
      value - 設定する値
=============================================================================================================*/
void PropertyBlock::SetFloat3(const std::string& name, const DirectX::XMFLOAT3& value)
{
    m_Properties[name] = value;
}

/*============================================================================================================
    Floatプロパティを設定する
    引数:
      name - プロパティ名
      value - 設定する値
=============================================================================================================*/
void PropertyBlock::SetFloat(const std::string& name, float value)
{
    m_Properties[name] = value;
}

/*============================================================================================================
    Float4プロパティを取得する
    引数:
      name - プロパティ名
      value - 取得した値を格納する変数
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool PropertyBlock::GetFloat4(const std::string& name, DirectX::XMFLOAT4& value) const
{
    auto it = m_Properties.find(name);
    if (it != m_Properties.end())
    {
        if (std::holds_alternative<DirectX::XMFLOAT4>(it->second))
        {
            value = std::get<DirectX::XMFLOAT4>(it->second);
            return true;
        }
    }
    return false;
}

/*============================================================================================================
    Float3プロパティを取得する
    引数:
      name - プロパティ名
      value - 取得した値を格納する変数
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool PropertyBlock::GetFloat3(const std::string& name, DirectX::XMFLOAT3& value) const
{
    auto it = m_Properties.find(name);
    if (it != m_Properties.end())
    {
        if (std::holds_alternative<DirectX::XMFLOAT3>(it->second))
        {
            value = std::get<DirectX::XMFLOAT3>(it->second);
            return true;
        }
    }
    return false;
}

/*============================================================================================================
    Floatプロパティを取得する
    引数:
      name - プロパティ名
      value - 取得した値を格納する変数
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool PropertyBlock::GetFloat(const std::string& name, float& value) const
{
    auto it = m_Properties.find(name);
    if (it != m_Properties.end())
    {
        if (std::holds_alternative<float>(it->second))
        {
            value = std::get<float>(it->second);
            return true;
        }
    }
    return false;
}

/*============================================================================================================
    プロパティが存在するか確認する
    引数:
      name - プロパティ名
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool PropertyBlock::HasProperty(const std::string& name) const
{
    return m_Properties.find(name) != m_Properties.end();
}

/*============================================================================================================
    すべてのプロパティをクリアする
=============================================================================================================*/
void PropertyBlock::Clear()
{
    m_Properties.clear();
}

/*============================================================================================================
    プロパティが空かどうかを確認する
    戻り値: プロパティが一つも設定されていない場合true
=============================================================================================================*/
bool PropertyBlock::IsEmpty() const
{
    return m_Properties.empty();
}

/*============================================================================================================
    すべてのプロパティ名を取得する
    戻り値: プロパティ名のリスト
=============================================================================================================*/
std::vector<std::string> PropertyBlock::GetPropertyNames() const
{
    std::vector<std::string> names;
    names.reserve(m_Properties.size());
    
    for (const auto& pair : m_Properties)
    {
        names.push_back(pair.first);
    }
    
    return names;
}
