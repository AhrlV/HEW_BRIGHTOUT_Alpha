#include "rendering/material_property_block.h"

/*============================================================================================================
    デフォルトコンストラクタ
    基底クラスのコンストラクタを呼び出す。
=============================================================================================================*/
MaterialPropertyBlock::MaterialPropertyBlock()
    : PropertyBlock()
    , m_OverrideTexture(nullptr)
{
}

/*============================================================================================================
    デストラクタ
=============================================================================================================*/
MaterialPropertyBlock::~MaterialPropertyBlock()
{
    m_OverrideTexture.reset();
}

/*============================================================================================================
    基本カラーを設定する
    シェーダーの"base_color"変数に書き込む
    引数:
      color - 基本カラー（RGBA）
=============================================================================================================*/
void MaterialPropertyBlock::SetBaseColor(const DirectX::XMFLOAT4& color)
{
    SetFloat4("base_color", color);
}

/*============================================================================================================
    拡散反射色を設定する
    シェーダーの"diffuse_color"変数に書き込む
    引数:
      color - 拡散反射色（RGBA）
=============================================================================================================*/
void MaterialPropertyBlock::SetDiffuseColor(const DirectX::XMFLOAT4& color)
{
    SetFloat4("diffuse_color", color);
}

/*============================================================================================================
    環境光色を設定する
    シェーダーの"ambient_color"変数に書き込む
    引数:
      color - 環境光色（RGBA）
=============================================================================================================*/
void MaterialPropertyBlock::SetAmbientColor(const DirectX::XMFLOAT4& color)
{
    SetFloat4("ambient_color", color);
}

/*============================================================================================================
    鏡面反射色を設定する
    シェーダーの"specular_color"変数に書き込む
    引数:
      color - 鏡面反射色（RGBA）
=============================================================================================================*/
void MaterialPropertyBlock::SetSpecularColor(const DirectX::XMFLOAT4& color)
{
    SetFloat4("specular_color", color);
}

/*============================================================================================================
    放射色を設定する
    シェーダーの"emissive_color"変数に書き込む
    引数:
      color - 放射色（RGBA）
=============================================================================================================*/
void MaterialPropertyBlock::SetEmissiveColor(const DirectX::XMFLOAT4& color)
{
    SetFloat4("emissive_color", color);
}

/*============================================================================================================
    基本カラーを取得する
    引数:
      color - 取得した値を格納する変数
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool MaterialPropertyBlock::GetBaseColor(DirectX::XMFLOAT4& color) const
{
    return GetFloat4("base_color", color);
}

/*============================================================================================================
    拡散反射色を取得する
    引数:
      color - 取得した値を格納する変数
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool MaterialPropertyBlock::GetDiffuseColor(DirectX::XMFLOAT4& color) const
{
    return GetFloat4("diffuse_color", color);
}

/*============================================================================================================
    環境光色を取得する
    引数:
      color - 取得した値を格納する変数
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool MaterialPropertyBlock::GetAmbientColor(DirectX::XMFLOAT4& color) const
{
    return GetFloat4("ambient_color", color);
}

/*============================================================================================================
    鏡面反射色を取得する
    引数:
      color - 取得した値を格納する変数
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool MaterialPropertyBlock::GetSpecularColor(DirectX::XMFLOAT4& color) const
{
    return GetFloat4("specular_color", color);
}

/*============================================================================================================
    放射色を取得する
    引数:
      color - 取得した値を格納する変数
    戻り値: プロパティが存在する場合true
=============================================================================================================*/
bool MaterialPropertyBlock::GetEmissiveColor(DirectX::XMFLOAT4& color) const
{
    return GetFloat4("emissive_color", color);
}

/*============================================================================================================
    テクスチャを設定する
    マテリアルのテクスチャをオーバーライドする。
    
    引数:
      texture - 設定するテクスチャのshared_ptr
=============================================================================================================*/
void MaterialPropertyBlock::SetTexture(std::shared_ptr<Texture> texture)
{
    m_OverrideTexture = texture;
}

/*============================================================================================================
    テクスチャを取得する
    戻り値: 設定されているテクスチャのshared_ptr（設定されていない場合はnullptr）
=============================================================================================================*/
std::shared_ptr<Texture> MaterialPropertyBlock::GetTexture() const
{
    return m_OverrideTexture;
}

/*============================================================================================================
    テクスチャが設定されているか確認する
    戻り値: テクスチャが設定されている場合true
=============================================================================================================*/
bool MaterialPropertyBlock::HasTexture() const
{
    return m_OverrideTexture != nullptr;
}

/*============================================================================================================
    テクスチャをクリアする
    設定されているテクスチャを解除する。
=============================================================================================================*/
void MaterialPropertyBlock::ClearTexture()
{
    m_OverrideTexture.reset();
}
