#include "resourcemanagement/resource.h"

/*============================================================================================================
    デフォルトコンストラクタ
    識別名は空文字列、クラスIDはUnknownで初期化される。
=============================================================================================================*/
Resource::Resource()
    : m_ClassID(ResourceClassID::Unknown)
    , m_Name(L"")
{
}

/*============================================================================================================
    クラスIDを指定するコンストラクタ
    引数:
      classID - リソースのクラスID
=============================================================================================================*/
Resource::Resource(ResourceClassID classID)
    : m_ClassID(classID)
    , m_Name(L"")
{
}

/*============================================================================================================
    識別名とクラスIDを指定するコンストラクタ
    引数:
      name - リソースの識別名
      classID - リソースのクラスID
=============================================================================================================*/
Resource::Resource(const std::wstring& name, ResourceClassID classID)
    : m_ClassID(classID)
    , m_Name(name)
{
}

/*============================================================================================================
    クラスIDを取得する
    戻り値: リソースのクラスID
=============================================================================================================*/
ResourceClassID Resource::GetClassID() const
{
    return m_ClassID;
}

/*============================================================================================================
    識別名を取得する
    戻り値: リソースの識別名
=============================================================================================================*/
const std::wstring& Resource::GetName() const
{
    return m_Name;
}

/*============================================================================================================
    クラスIDを設定する
    引数:
      classID - 設定するクラスID
=============================================================================================================*/
void Resource::SetClassID(ResourceClassID classID)
{
    m_ClassID = classID;
}

/*============================================================================================================
    識別名を設定する
    引数:
      name - 設定する識別名
=============================================================================================================*/
void Resource::SetName(const std::wstring& name)
{
    m_Name = name;
}
